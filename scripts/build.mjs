#!/usr/bin/env node
/**
 * ACHIEVE ABOARD — static site generator
 * ----------------------------------------------------------------
 *   npm run build
 *
 * Reads /content/*.js and writes the website's HTML files next to
 * index.html. No dependencies, no database: just Node.js 18+.
 */
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadContent, PAGE_KEYS } from './lib/content.mjs';
import { createCtx, PAGE_FILES } from './lib/ctx.mjs';
import { render404, renderDocument } from './templates/layout.mjs';
import { blogPostPage, PAGE_BUILDERS, postPath } from './templates/pages.mjs';

export const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const GENERATED_MARK = 'Generated by scripts/build.mjs';

function writeIfChanged(rel, data) {
  const file = path.join(ROOT, rel);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  if (fs.existsSync(file) && fs.readFileSync(file, 'utf8') === data) return false;
  fs.writeFileSync(file, data);
  return true;
}

function fileHash(rel) {
  const file = path.join(ROOT, rel);
  if (!fs.existsSync(file)) return '';
  return crypto.createHash('sha1').update(fs.readFileSync(file)).digest('hex').slice(0, 8);
}

export async function build({ quiet = false } = {}) {
  const started = Date.now();
  const log = (...a) => !quiet && console.log(...a);

  const { c, errors, warnings } = await loadContent(ROOT);
  if (errors.length) {
    const msg = `\nThe build stopped because of ${errors.length} problem${errors.length > 1 ? 's' : ''} in the content files:\n\n${errors
      .map((e) => `  ✖ ${e}`)
      .join('\n')}\n\nFix the line(s) above, save, and run the build again.\n`;
    const e = new Error(msg);
    e.userFacing = true;
    throw e;
  }

  const assetVersion = {
    'assets/css/styles.css': fileHash('assets/css/styles.css'),
    'assets/js/main.js': fileHash('assets/js/main.js'),
  };
  const site = c.site;
  const written = [];
  const outputs = new Set();

  const emit = (rel, html) => {
    outputs.add(rel);
    if (writeIfChanged(rel, html)) written.push(rel);
  };

  // ---- main pages
  for (const key of PAGE_KEYS) {
    const file = PAGE_FILES[key];
    const ctx = createCtx({ root: ROOT, c, page: key, file, depth: 0, assetVersion });
    const page = PAGE_BUILDERS[key](ctx);
    emit(file, renderDocument(ctx, page));
  }

  // ---- blog posts
  for (const post of c.blog) {
    const file = postPath(post);
    const ctx = createCtx({ root: ROOT, c, page: 'blog', file, depth: 1, assetVersion });
    emit(file, renderDocument(ctx, blogPostPage(ctx, post)));
  }

  // ---- remove blog pages for posts that no longer exist (only files this script made)
  const blogDir = path.join(ROOT, 'blog');
  if (fs.existsSync(blogDir)) {
    for (const f of fs.readdirSync(blogDir)) {
      const rel = `blog/${f}`;
      if (f.endsWith('.html') && !outputs.has(rel)) {
        const text = fs.readFileSync(path.join(blogDir, f), 'utf8');
        if (text.includes(GENERATED_MARK)) {
          fs.unlinkSync(path.join(blogDir, f));
          written.push(`${rel} (removed)`);
        }
      }
    }
  }

  // ---- 404
  emit('404.html', render404(createCtx({ root: ROOT, c, page: 'home', file: '404.html', depth: 0, assetVersion })));

  // ---- robots + sitemap
  const today = new Date().toISOString().slice(0, 10);
  emit(
    'robots.txt',
    `User-agent: *\nAllow: /\n${site.url ? `\nSitemap: ${site.url}/sitemap.xml\n` : ''}`,
  );
  if (site.url) {
    const urls = [
      ...PAGE_KEYS.map((k) => ({
        loc: `${site.url}/${PAGE_FILES[k] === 'index.html' ? '' : PAGE_FILES[k]}`,
        lastmod: today,
        priority: k === 'home' ? '1.0' : k === 'privacy' ? '0.3' : '0.8',
      })),
      ...c.blog.map((p) => ({ loc: `${site.url}/${postPath(p)}`, lastmod: p.date, priority: '0.6' })),
    ];
    emit(
      'sitemap.xml',
      `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls
        .map(
          (u) =>
            `  <url><loc>${u.loc}</loc><lastmod>${u.lastmod}</lastmod><priority>${u.priority}</priority></url>`,
        )
        .join('\n')}\n</urlset>\n`,
    );
  } else if (fs.existsSync(path.join(ROOT, 'sitemap.xml'))) {
    fs.unlinkSync(path.join(ROOT, 'sitemap.xml'));
  }

  // ---- web app manifest
  emit(
    'site.webmanifest',
    `${JSON.stringify(
      {
        name: site.brand.shortName,
        short_name: site.brand.shortName,
        description: site.brand.description,
        start_url: './index.html',
        scope: './',
        display: 'standalone',
        background_color: '#ffffff',
        theme_color: site.seo.themeColor,
        icons: [
          { src: 'assets/img/icons/icon-192.png', sizes: '192x192', type: 'image/png' },
          { src: 'assets/img/icons/icon-512.png', sizes: '512x512', type: 'image/png' },
        ],
      },
      null,
      2,
    )}\n`,
  );

  // ---- hosting helpers
  emit('.nojekyll', ''); // tells GitHub Pages to serve every file as-is
  emit(
    '_headers',
    `# Used by Netlify and Cloudflare Pages (ignored by other hosts).
/*
  X-Content-Type-Options: nosniff
  Referrer-Policy: strict-origin-when-cross-origin
  Permissions-Policy: camera=(), microphone=(), geolocation=()

/assets/css/*
  Cache-Control: public, max-age=31536000, immutable

/assets/js/*
  Cache-Control: public, max-age=31536000, immutable

/assets/fonts/*
  Cache-Control: public, max-age=31536000, immutable

/assets/img/*
  Cache-Control: public, max-age=2592000

/*.html
  Cache-Control: public, max-age=0, must-revalidate
`,
  );

  const ms = Date.now() - started;
  log(
    `✔ Built ${PAGE_KEYS.length + c.blog.length + 1} pages in ${ms} ms` +
      (written.length ? ` (${written.length} file${written.length === 1 ? '' : 's'} updated)` : ' (no changes)'),
  );
  if (warnings.length) {
    log(`\n⚠ ${warnings.length} thing${warnings.length === 1 ? '' : 's'} to review before launch:`);
    for (const w of warnings) log(`  • ${w}`);
    log('');
  }
  return { c, written, warnings };
}

// Run directly: `node scripts/build.mjs`
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  build().catch((e) => {
    console.error(e.userFacing ? e.message : e);
    process.exit(1);
  });
}
